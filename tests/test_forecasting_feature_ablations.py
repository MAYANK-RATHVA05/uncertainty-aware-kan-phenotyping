def _data_and_definitions(saved_forecasting_data):
    directory, _, _ = saved_forecasting_data
    data = baselines.load_baseline_data(directory)
    return data, ablations.feature_set_definitions(data.preprocessor)


def _assert_group_matches_fitted_metadata(groups, transformer, block, offset, names):
    """Verify raw-feature membership against positions in the fitted pipelines."""
    by_name = {group["original_feature"]: group for group in groups if group["block"] == block}
    for kind, pipeline, columns in transformer.transformers_:
        if kind == "remainder":
            continue
        output = transformer.output_indices_[kind]
        start = offset + output.start
        if kind == "numeric":
            indicator = pipeline.named_steps["imputer"].indicator_.features_
            for position, raw_name in enumerate(columns):
                expected = [start + position]
                expected.extend(start + len(columns) + index
                                for index, raw_position in enumerate(indicator)
                                if int(raw_position) == position)
                assert by_name[raw_name]["column_indices"] == expected
                assert by_name[raw_name]["feature_names"] == [names[index] for index in expected]
        elif kind == "categorical":
            encoder = pipeline.named_steps["encoder"]
            current = start
            for raw_name, categories in zip(columns, encoder.categories_, strict=True):
                expected = list(range(current, current + len(categories)))
                assert by_name[raw_name]["column_indices"] == expected
                assert by_name[raw_name]["feature_names"] == [names[index] for index in expected]
                current += len(categories)
            assert current == offset + output.stop
        else:
            raise AssertionError(f"Unexpected fitted transformer kind: {kind}")


def test_original_feature_groups_cover_every_encoded_column_once(saved_forecasting_data):
    data, _ = _data_and_definitions(saved_forecasting_data)
    groups = ablations.original_feature_groups(data.preprocessor)
    names = data.preprocessor.feature_names["tabular"]
    expected = ({("SM1", name) for name in WEARABLE_STATISTICS_FEATURES}
                | {("SM2", name) for name in WEARABLE_STATISTICS_FEATURES}
                | {("demographics", name) for name in BASELINE_DEMOGRAPHIC_FEATURES}
                | {("SM0", "phq9_score_start")})
    assert {(group["block"], group["original_feature"]) for group in groups} == expected
    assert len(groups) == len(expected)
    covered = [index for group in groups for index in group["column_indices"]]
    assert sorted(covered) == list(range(len(names)))
    assert len(covered) == len(set(covered))
    for group in groups:
        assert group["column_indices"]
        assert group["feature_names"] == [names[index] for index in group["column_indices"]]


def test_group_selection_keeps_missing_indicators_and_whole_onehot_features(saved_forecasting_data):
    data, definitions = _data_and_definitions(saved_forecasting_data)
    processor = data.preprocessor
    groups = ablations.original_feature_groups(processor)
    names = processor.feature_names["tabular"]
    wearable_width = len(processor.feature_names["wearable"])
    for block, offset in (("SM1", 0), ("SM2", wearable_width)):
        _assert_group_matches_fitted_metadata(groups, processor.wearable_transformer,
                                             block, offset, names)
    _assert_group_matches_fitted_metadata(groups, processor.demographic_transformer,
                                         "demographics", 2 * wearable_width, names)
    demographic_groups = [group for group in groups if group["block"] == "demographics"]
    assert any(len(group["column_indices"]) > 1 for group in demographic_groups), \
        "The fixture must exercise a multi-column categorical feature."
    # A chosen original feature is always included as a whole: its numeric value
    # and missingness flag, or every fitted category, travel together.
    for definition in definitions.values():
        selected = set(definition["column_indices"])
        for group in groups:
            intersection = selected.intersection(group["column_indices"])
            assert not intersection or intersection == set(group["column_indices"])


def test_ablations_are_nested_and_preserve_saved_month_and_column_order(saved_forecasting_data):
    data, definitions = _data_and_definitions(saved_forecasting_data)
    assert set(definitions) == {"A", "B", "C", "D"}
    expected_blocks = {
        "A": {"SM0"}, "B": {"SM0", "demographics"},
        "C": {"SM0", "demographics", "SM2"},
        "D": {"SM0", "demographics", "SM1", "SM2"},
    }
    names = data.preprocessor.feature_names["tabular"]
    for key, definition in definitions.items():
        indices = definition["column_indices"]
        assert indices == sorted(set(indices)), "Keep the existing matrix column order."
        assert definition["feature_names"] == [names[index] for index in indices]
        assert {group["block"] for group in definition["original_feature_groups"]} == expected_blocks[key]
    for earlier, later in zip("ABC", "BCD", strict=True):
        assert set(definitions[earlier]["column_indices"]) < set(definitions[later]["column_indices"])
    assert definitions["A"]["feature_names"] == ["measured_sm0_phq9_standardized"]
    assert definitions["D"]["feature_names"] == names
    assert definitions["D"]["column_indices"] == list(range(len(names)))
    assert not any(name.startswith("SM1__") for name in definitions["C"]["feature_names"])
    assert any(name.startswith("SM2__") for name in definitions["C"]["feature_names"])


def test_fitted_missingness_indicators_remain_with_their_original_feature(saved_forecasting_data):
    directory, _, dataset = saved_forecasting_data
    data = baselines.load_baseline_data(directory)
    predictors = deepcopy(dataset.predictors)
    sample = int(data.train.sample_indices[0])
    raw_wearable = WEARABLE_STATISTICS_FEATURES[0]
    predictors.wearable.iloc[2 * sample, predictors.wearable.columns.get_loc(raw_wearable)] = np.nan
    predictors.demographics.iloc[sample, predictors.demographics.columns.get_loc("height")] = np.nan
    # Fit only this deliberately modified synthetic predictor payload. This
    # exercises actual sklearn indicator metadata without changing real data.
    processor = ConditionalForecastPreprocessor().fit(predictors, data.train.sample_indices)
    groups = ablations.original_feature_groups(processor)
    definitions = ablations.feature_set_definitions(processor)
    by_key = {(group["block"], group["original_feature"]): group for group in groups}
    for block in ("SM1", "SM2"):
        group = by_key[block, raw_wearable]
        assert len(group["column_indices"]) == 2
        assert any("missingindicator" in name for name in group["feature_names"])
        assert set(group["column_indices"]).issubset(definitions["D"]["column_indices"])
        assert bool(set(group["column_indices"]) & set(definitions["C"]["column_indices"])) == (block == "SM2")
        assert not set(group["column_indices"]) & set(definitions["B"]["column_indices"])
    demographic_group = by_key["demographics", "height"]
    assert len(demographic_group["column_indices"]) == 2
    assert set(demographic_group["column_indices"]).issubset(definitions["B"]["column_indices"])


@pytest.mark.parametrize("tampering", ["missing_onehot_column", "wrong_name", "wrong_month"])
def test_partial_or_mislabeled_feature_definitions_are_rejected(saved_forecasting_data, tampering):
    data, definitions = _data_and_definitions(saved_forecasting_data)
    bad = deepcopy(definitions["C"])
    if tampering == "missing_onehot_column":
        group = next(group for group in bad["original_feature_groups"]
                     if group["block"] == "demographics" and len(group["column_indices"]) > 1)
        bad["column_indices"].remove(group["column_indices"][-1])
    elif tampering == "wrong_name":
        bad["feature_names"][0] = "undocumented_or_generated_feature"
    else:
        group = next(group for group in bad["original_feature_groups"] if group["block"] == "SM2")
        group["block"] = "SM1"
    with pytest.raises(ValueError, match="complete|reviewed|feature"):
        ablations.fit_ridge_ablation(data, bad)


@pytest.mark.parametrize("setup", ["A", "B", "C", "D"])
def test_each_alpha_uses_only_training_rows_and_the_requested_columns(
    saved_forecasting_data, monkeypatch, setup
):
    data, definitions = _data_and_definitions(saved_forecasting_data)
    definition = definitions[setup]
    indices = definition["column_indices"]
    calls = []
    original_fit = Ridge.fit

    def record_fit(model, x, y, *args, **kwargs):
        calls.append((float(model.alpha), np.asarray(x).copy(), np.asarray(y).copy()))
        return original_fit(model, x, y, *args, **kwargs)

    monkeypatch.setattr(Ridge, "fit", record_fit)
    result = ablations.fit_ridge_ablation(data, definition)
    assert [call[0] for call in calls] == list(baselines.ALPHAS)
    assert len(calls) == 5, "Do not refit the selected model with validation observations."
    for _, x, y in calls:
        assert x.dtype == np.float64
        assert y.dtype == np.float64
        np.testing.assert_array_equal(x, data.train.tabular[:, indices])
        np.testing.assert_array_equal(y, data.train.targets)
    assert [candidate["alpha"] for candidate in result.candidates] == list(baselines.ALPHAS)
    selected = min(result.candidates, key=lambda value: value["validation_metrics"]["rmse"])
    assert result.selected_alpha == selected["alpha"]
    assert result.model.alpha == result.selected_alpha
    assert result.model.solver == "svd"
    assert result.predictions.shape == data.validation.targets.shape
    np.testing.assert_allclose(result.predictions,
                               result.model.predict(data.validation.tabular[:, indices]),
                               rtol=0, atol=1e-10)
    assert result.metrics == baselines.regression_metrics(data.validation.targets, result.predictions)


@pytest.mark.parametrize("setup", ["A", "B", "C"])
def test_excluded_sm1_values_cannot_affect_fit_or_predictions(saved_forecasting_data, setup):
    data, definitions = _data_and_definitions(saved_forecasting_data)
    excluded = [index for index, name in enumerate(data.preprocessor.feature_names["tabular"])
                if name.startswith("SM1__")]
    changed = deepcopy(data)
    for partition_name in ("train", "validation"):
        partition = getattr(changed, partition_name)
        x = partition.tabular.copy()
        x[:, excluded] = np.arange(len(excluded))[None, :] + 1e8
        changed = replace(changed, **{partition_name: replace(partition, tabular=x)})
    first = ablations.fit_ridge_ablation(data, definitions[setup])
    second = ablations.fit_ridge_ablation(changed, definitions[setup])
    assert first.selected_alpha == second.selected_alpha
    assert first.metrics == second.metrics
    np.testing.assert_array_equal(first.model.coef_, second.model.coef_)
    np.testing.assert_array_equal(first.model.intercept_, second.model.intercept_)
    np.testing.assert_array_equal(first.predictions, second.predictions)


def test_validation_outcomes_cannot_change_any_candidate_coefficients(saved_forecasting_data):
    data, definitions = _data_and_definitions(saved_forecasting_data)
    changed = replace(data, validation=replace(data.validation,
                      targets=np.full_like(data.validation.targets, 27)))
    for definition in definitions.values():
        first = ablations.fit_ridge_ablation(data, definition)
        second = ablations.fit_ridge_ablation(changed, definition)
        for model1, model2 in zip(first.models, second.models, strict=True):
            assert model1.alpha == model2.alpha
            np.testing.assert_array_equal(model1.coef_, model2.coef_)
            np.testing.assert_array_equal(model1.intercept_, model2.intercept_)


