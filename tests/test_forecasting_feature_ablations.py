def test_runner_never_reads_reserved_payloads_or_refits_preprocessing_and_preserves_inputs(
    saved_forecasting_data, tmp_path, monkeypatch
):
    directory, _, _ = saved_forecasting_data
    baseline_dir = tmp_path / "existing_baselines"
    baselines.run_forecasting_baselines(directory, baseline_dir)
    before_data = {path.name: sha256_file(path) for path in directory.iterdir()}
    before_baseline = {path.name: sha256_file(path) for path in baseline_dir.iterdir()}
    forbidden = {f"{partition}_{kind}.npz" for partition in ("calibration", "test")
                 for kind in ("inputs", "targets")}
    original_open = Path.open
    original_load = np.load

    def guarded_open(path, *args, **kwargs):
        assert path.name not in forbidden, f"Reserved payload was opened: {path.name}"
        return original_open(path, *args, **kwargs)

    def guarded_load(path, *args, **kwargs):
        if isinstance(path, (str, Path)):
            assert Path(path).name not in forbidden
        return original_load(path, *args, **kwargs)

    def deny_transform_or_fit(*_args, **_kwargs):
        raise AssertionError("Ablations must reuse saved transformed matrices and fitted preprocessing.")

    monkeypatch.setattr(Path, "open", guarded_open)
    monkeypatch.setattr(np, "load", guarded_load)
    monkeypatch.setattr(ConditionalForecastPreprocessor, "fit", deny_transform_or_fit)
    monkeypatch.setattr(ConditionalForecastPreprocessor, "transform", deny_transform_or_fit)
    report = ablations.run_feature_ablations(directory, baseline_dir, tmp_path / "ablations")
    assert isinstance(report, dict)
    monkeypatch.undo()
    assert before_data == {path.name: sha256_file(path) for path in directory.iterdir()}
    assert before_baseline == {path.name: sha256_file(path) for path in baseline_dir.iterdir()}


def test_runner_saves_aligned_predictions_exact_feature_lists_and_reusable_full_ridge(
    saved_forecasting_data, tmp_path
):
    directory, _, _ = saved_forecasting_data
    baseline_dir = tmp_path / "existing_baselines"
    baseline_report = baselines.run_forecasting_baselines(directory, baseline_dir)
    data, definitions = _data_and_definitions(saved_forecasting_data)
    output = tmp_path / "ablations"
    summary = ablations.run_feature_ablations(directory, baseline_dir, output)
    assert summary == json.loads((output / "summary.json").read_text())
    assert set(summary["setups"]) == {"A", "B", "C", "D"}
    assert set(summary["increments"]) == {"B_minus_A", "C_minus_B", "D_minus_C"}
    assert json.loads((output / "feature_groups.json").read_text()) == \
        ablations.original_feature_groups(data.preprocessor)
    assert sha256_file(output / "preprocessor.joblib") == sha256_file(directory / "preprocessor.joblib")
    with np.load(output / "used_split_indices.npz", allow_pickle=False) as splits:
        assert set(splits.files) == {"train", "validation"}
        np.testing.assert_array_equal(splits["train"], data.train.sample_indices)
        np.testing.assert_array_equal(splits["validation"], data.validation.sample_indices)
    saved_predictions = {}
    for setup, definition in definitions.items():
        setup_dir = output / setup
        assert json.loads((setup_dir / "features.json").read_text()) == definition
        selected_model = joblib.load(setup_dir / "selected_ridge.joblib")
        candidates = joblib.load(setup_dir / "ridge_candidates.joblib")
        assert [model.alpha for model in candidates] == list(baselines.ALPHAS)
        metrics = json.loads((setup_dir / "validation_metrics.json").read_text())
        assert metrics == summary["setups"][setup]
        assert metrics["selected_alpha"] == selected_model.alpha
        assert metrics["feature_count"] == len(definition["column_indices"])
        with np.load(setup_dir / "validation_predictions.npz", allow_pickle=False) as archive:
            np.testing.assert_array_equal(archive["sample_indices"], data.validation.sample_indices)
            np.testing.assert_array_equal(archive["measured_sm3"], data.validation.targets)
            prediction = archive["prediction"].copy()
        np.testing.assert_allclose(prediction,
            selected_model.predict(data.validation.tabular[:, definition["column_indices"]]),
            rtol=0, atol=1e-10)
        assert metrics["metrics"] == baselines.regression_metrics(data.validation.targets, prediction)
        saved_predictions[setup] = prediction
    assert summary["setups"]["D"]["selected_alpha"] == baseline_report["selected_alpha"]
    assert summary["setups"]["D"]["metrics"] == baseline_report["metrics"]["ridge"]
    with np.load(baseline_dir / "validation_predictions.npz", allow_pickle=False) as old_predictions:
        np.testing.assert_array_equal(saved_predictions["D"], old_predictions["ridge"])
    assert (output / "D" / "reproduction.json").is_file()
    old_model = joblib.load(baseline_dir / "models.joblib")["ridge"]
    reused_model = joblib.load(output / "D" / "selected_ridge.joblib")
    np.testing.assert_array_equal(old_model.coef_, reused_model.coef_)
    np.testing.assert_array_equal(old_model.intercept_, reused_model.intercept_)
    for pair, earlier, later in (("B_minus_A", "A", "B"),
                                 ("C_minus_B", "B", "C"),
                                 ("D_minus_C", "C", "D")):
        for metric in ("mae", "rmse", "r2"):
            assert summary["increments"][pair][metric] == pytest.approx(
                summary["setups"][later]["metrics"][metric]
                - summary["setups"][earlier]["metrics"][metric])


def test_runner_rejects_incompatible_full_ridge_source_without_overwriting_it(
    saved_forecasting_data, tmp_path
):
    directory, _, _ = saved_forecasting_data
    baseline_dir = tmp_path / "existing_baselines"
    baselines.run_forecasting_baselines(directory, baseline_dir)
    prediction_path = baseline_dir / "validation_predictions.npz"
    with np.load(prediction_path, allow_pickle=False) as archive:
        arrays = {name: archive[name].copy() for name in archive.files}
    arrays["ridge"] = arrays["ridge"] + 1
    np.savez_compressed(prediction_path, **arrays)
    tampered_hash = sha256_file(prediction_path)
    with pytest.raises(ValueError, match="hash|SHA|sha|integrity|reproduc|baseline|Baseline"):
        ablations.run_feature_ablations(directory, baseline_dir, tmp_path / "bad_ablations")
    assert sha256_file(prediction_path) == tampered_hash
